using System.Globalization;
using System.Text;

namespace PbiTwin.Core.Verify;

public enum CheckStatus
{
    Pass,
    Warn,
    Fail,
}

public sealed record Check(string Name, CheckStatus Status, string Detail);

public sealed record TableCount(string Table, long Original, long Twin, bool Limited);

public sealed record LinkCheck(string Relationship, long TwinOrphans, long? OriginalOrphans, bool OneSideUnique);

public sealed record ColumnRuleRow(string Column, string Class, string Rule, string Domain);

/// <summary>
/// The result of verifying a twin. Contains counts, statuses and column names — never original values,
/// the seed, or the scaling parameters.
/// </summary>
public sealed class TrustReport
{
    public required string TwinName { get; init; }

    public List<Check> Checks { get; } = [];

    public List<TableCount> Tables { get; } = [];

    public List<LinkCheck> Links { get; } = [];

    public List<LeakFinding> Leaks { get; } = [];

    public int LeakValuesChecked { get; set; }

    public int LeakFilesScanned { get; set; }

    public List<ColumnRuleRow> Columns { get; } = [];

    public Dictionary<string, int> LiteralReplacements { get; } = [];

    public List<string> SkippedTables { get; } = [];

    public List<string> Warnings { get; } = [];

    public bool Passed => Checks.TrueForAll(c => c.Status != CheckStatus.Fail);

    public string ToMarkdown()
    {
        var inv = CultureInfo.InvariantCulture;
        var sb = new StringBuilder();
        sb.AppendLine(inv, $"# Trust report: {TwinName}");
        sb.AppendLine();
        sb.AppendLine("Generated by PbiTwin. This report contains no original values, no seed and no scaling parameters.");
        sb.AppendLine();
        sb.AppendLine(Passed ? "**Result: all checks passed.**" : "**Result: some checks FAILED. Do not share this twin before reviewing them.**");
        sb.AppendLine();

        sb.AppendLine("## Checks");
        sb.AppendLine();
        sb.AppendLine("| | Check | Detail |");
        sb.AppendLine("|---|---|---|");
        foreach (var c in Checks)
        {
            sb.AppendLine(inv, $"| {Icon(c.Status)} | {Escape(c.Name)} | {Escape(c.Detail)} |");
        }

        sb.AppendLine();
        sb.AppendLine("## Row counts");
        sb.AppendLine();
        sb.AppendLine("| Table | Original | Twin | Note |");
        sb.AppendLine("|---|---:|---:|---|");
        foreach (var t in Tables)
        {
            sb.AppendLine(inv, $"| {Escape(t.Table)} | {t.Original:N0} | {t.Twin:N0} | {(t.Limited ? "row limit applied" : string.Empty)} |");
        }

        if (Links.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Relationships");
            sb.AppendLine();
            sb.AppendLine("| Relationship | Keys without match (twin) | (original) | One side unique |");
            sb.AppendLine("|---|---:|---:|---|");
            foreach (var l in Links)
            {
                sb.AppendLine(inv, $"| {Escape(l.Relationship)} | {l.TwinOrphans:N0} | {(l.OriginalOrphans is { } o ? o.ToString("N0", inv) : "n/a")} | {(l.OneSideUnique ? "yes" : "**no**")} |");
            }
        }

        sb.AppendLine();
        sb.AppendLine("## Leak scan");
        sb.AppendLine();
        sb.AppendLine(inv, $"{LeakValuesChecked:N0} distinct original text values (4+ characters) were searched for in {LeakFilesScanned:N0} output files.");
        sb.AppendLine();
        if (Leaks.Count == 0)
        {
            sb.AppendLine("**0 leaks found.**");
        }
        else
        {
            sb.AppendLine(inv, $"**{Leaks.Count:N0} leaks found** (values are not shown):");
            sb.AppendLine();
            sb.AppendLine("Summary by column (start here):");
            sb.AppendLine();
            sb.AppendLine("| Value from column | Matches | Files |");
            sb.AppendLine("|---|---:|---:|");
            foreach (var g in Leaks.GroupBy(l => l.Columns, StringComparer.Ordinal).OrderByDescending(g => g.Count()).Take(50))
            {
                sb.AppendLine(inv, $"| {Escape(g.Key)} | {g.Count():N0} | {g.Select(l => l.File).Distinct(StringComparer.Ordinal).Count():N0} |");
            }

            sb.AppendLine();
            sb.AppendLine(inv, $"First {Math.Min(200, Leaks.Count)} matches:");
            sb.AppendLine();
            sb.AppendLine("| File | Line | Value from column |");
            sb.AppendLine("|---|---:|---|");
            foreach (var l in Leaks.Take(200))
            {
                sb.AppendLine(inv, $"| {Escape(l.File)} | {l.Line} | {Escape(l.Columns)} |");
            }
        }

        if (LiteralReplacements.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Literals replaced in DAX and report");
            sb.AppendLine();
            sb.AppendLine("| Location | Replacements |");
            sb.AppendLine("|---|---:|");
            foreach (var (where, n) in LiteralReplacements.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            {
                sb.AppendLine(inv, $"| {Escape(where)} | {n} |");
            }
        }

        if (Warnings.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Warnings");
            sb.AppendLine();
            foreach (var w in Warnings)
            {
                sb.AppendLine(inv, $"- {w}");
            }
        }

        if (SkippedTables.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("## Not extracted (recalculated by Power BI)");
            sb.AppendLine();
            foreach (var s in SkippedTables)
            {
                sb.AppendLine(inv, $"- {s}");
            }
        }

        sb.AppendLine();
        sb.AppendLine("## Column rules");
        sb.AppendLine();
        sb.AppendLine("| Column | Detected as | Rule | Shared mapping |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var c in Columns)
        {
            sb.AppendLine(inv, $"| {Escape(c.Column)} | {c.Class} | {c.Rule} | {Escape(c.Domain)} |");
        }

        return sb.ToString();
    }

    private static string Icon(CheckStatus s) => s switch
    {
        CheckStatus.Pass => "✅",
        CheckStatus.Warn => "⚠️",
        _ => "❌",
    };

    private static string Escape(string s) => s.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}
